import os


# ============================================================
# 配置
# ============================================================

LABEL_DIR = r"D:\PycharmProjects\computer_controller\make_dataset\train\labels"


# ============================================================
# 顶部错误框
# ============================================================

TOP_Y_THRESHOLD = 0.10


# ============================================================
# 左下 / 右下大型错误框
# ============================================================

BOTTOM_Y_THRESHOLD = 0.85
BOTTOM_WIDTH_THRESHOLD = 0.20
BOTTOM_HEIGHT_THRESHOLD = 0.15


# ============================================================
# 判断是否为错误框
# ============================================================

def is_wrong_box(cx, cy, w, h):

    # --------------------------------------------------------
    # 1. 顶部错误框
    # --------------------------------------------------------
    # 例如：
    # 0 0.722177 0.025107 0.018821 0.027074
    #
    # center_y 非常靠近顶部
    # --------------------------------------------------------

    if cy < TOP_Y_THRESHOLD:
        return True


    # --------------------------------------------------------
    # 2. 左下 / 右下大型错误框
    # --------------------------------------------------------
    # 例如：
    #
    # 0 0.752326 0.882614 0.235071 0.228191
    # 0 0.297561 0.903206 0.304351 0.188197
    # --------------------------------------------------------

    if (
        cy > BOTTOM_Y_THRESHOLD
        and w > BOTTOM_WIDTH_THRESHOLD
        and h > BOTTOM_HEIGHT_THRESHOLD
    ):
        return True


    # --------------------------------------------------------
    # 正常框
    # --------------------------------------------------------

    return False


# ============================================================
# 获取标签文件
# ============================================================

label_files = [
    f
    for f in os.listdir(LABEL_DIR)
    if f.lower().endswith(".txt")
]

label_files.sort()


# ============================================================
# 统计
# ============================================================

total_files = 0
modified_files = 0

total_boxes = 0
deleted_boxes = 0

top_deleted = 0
bottom_deleted = 0


# ============================================================
# 开始
# ============================================================

print("=" * 80)
print("开始清理错误标注")
print("=" * 80)

print(f"标签目录: {LABEL_DIR}")
print()
print("删除规则:")
print(f"  顶部: center_y < {TOP_Y_THRESHOLD}")
print(
    f"  底部: center_y > {BOTTOM_Y_THRESHOLD} "
    f"AND width > {BOTTOM_WIDTH_THRESHOLD} "
    f"AND height > {BOTTOM_HEIGHT_THRESHOLD}"
)
print()
print(f"标签文件数量: {len(label_files)}")

print("=" * 80)


# ============================================================
# 遍历所有标签
# ============================================================

for filename in label_files:

    path = os.path.join(
        LABEL_DIR,
        filename
    )

    total_files += 1


    # --------------------------------------------------------
    # 读取
    # --------------------------------------------------------

    with open(
        path,
        "r",
        encoding="utf-8"
    ) as f:

        lines = f.readlines()


    new_lines = []

    file_deleted = 0


    # --------------------------------------------------------
    # 遍历每一个框
    # --------------------------------------------------------

    for line in lines:

        line = line.strip()


        # 空行
        if not line:
            continue


        parts = line.split()


        # ----------------------------------------------------
        # 检查格式
        # ----------------------------------------------------

        if len(parts) != 5:

            print(
                f"[警告] 格式错误: {filename}"
            )

            new_lines.append(line)

            continue


        try:

            class_id = parts[0]

            cx = float(parts[1])
            cy = float(parts[2])
            w = float(parts[3])
            h = float(parts[4])

        except ValueError:

            print(
                f"[警告] 数值错误: {filename}"
            )

            new_lines.append(line)

            continue


        total_boxes += 1


        # ====================================================
        # 判断错误框
        # ====================================================

        if is_wrong_box(
            cx,
            cy,
            w,
            h
        ):

            deleted_boxes += 1
            file_deleted += 1


            # ------------------------------------------------
            # 判断是哪一种错误
            # ------------------------------------------------

            if cy < TOP_Y_THRESHOLD:

                top_deleted += 1

                error_type = "顶部"


            else:

                bottom_deleted += 1

                error_type = "底部"


            # ------------------------------------------------
            # 输出
            # ------------------------------------------------

            print(
                f"[删除-{error_type}] "
                f"{filename:30s} "
                f"cx={cx:.6f} "
                f"cy={cy:.6f} "
                f"w={w:.6f} "
                f"h={h:.6f}"
            )


            continue


        # ====================================================
        # 正常框
        # ====================================================

        new_lines.append(line)


    # ========================================================
    # 保存
    # ========================================================

    if file_deleted > 0:

        with open(
            path,
            "w",
            encoding="utf-8"
        ) as f:

            f.write(
                "\n".join(new_lines)
            )

            if new_lines:
                f.write("\n")


        modified_files += 1


# ============================================================
# 完成
# ============================================================

print()
print("=" * 80)
print("清理完成")
print("=" * 80)

print(f"标签文件总数:       {total_files}")
print(f"修改文件数量:       {modified_files}")

print()

print(f"原始标注数量:       {total_boxes}")

print(f"删除顶部错误框:     {top_deleted}")
print(f"删除底部错误框:     {bottom_deleted}")

print(f"删除错误框总数:     {deleted_boxes}")

print(
    f"剩余标注数量:       "
    f"{total_boxes - deleted_boxes}"
)

print("=" * 80)